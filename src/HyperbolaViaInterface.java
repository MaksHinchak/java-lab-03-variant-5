import java.util.Objects; // Потрібно для узгодженого hashCode.
// class описує тип об’єктів; new створює конкретний об’єкт і викликає його конструктор. public робить клас
// доступним ззовні; final у заголовку класу, якщо він є, забороняє створювати підкласи, але сам по собі не робить
// поля незмінними.
// implements означає обіцянку виконати контракт інтерфейсу. Comparable<T> вимагає compareTo для природного
// порядку; Comparator<T> — окремий compare для зовнішнього правила сортування; FunctionLike — value і print для
// кривої.
public final class HyperbolaViaInterface implements FunctionLike { // Ця реалізація не успадковує абстрактний Function.
    // private забороняє прямий доступ до поля з інших класів. final дозволяє присвоїти поле лише один раз; для
    // посилання це заборона замінити об’єкт, а не заборона змінювати його вміст, якщо сам об’єкт змінний.
    private final double a; // Інтерфейс не має полів екземпляра, тому стан зберігає реалізатор.
    private final double b; // Друга піввісь кривої.
    public HyperbolaViaInterface(double a, double b) { // Конструктор класу, який реалізує контракт.
        // Double.isFinite(...) повертає true лише для звичайного скінченного числа; ! заперечує результат. double
        // може містити NaN («не число») і ±Infinity, тому успішний parseDouble ще не гарантує придатність числа
        // для формули. У Python аналог — math.isfinite(x); ця перевірка не перевіряє точність округлення.
        // throw — аналог raise у Python: негайно припиняємо звичайний хід методу й передаємо об’єкт помилки
        // найближчому відповідному catch. new створює виняток, а текст конструктора пояснює причину користувачу.
        // 1e100 — науковий запис числа 10 у степені 100. Верхня межа навмисно нижча за максимум double, щоб
        // подальші формули мали запас; вона не змінює тип і не означає округлення значення.
        if (!Double.isFinite(a) || !Double.isFinite(b) || a <= 0 || b <= 0 || a > 1e100 || b > 1e100) throw new IllegalArgumentException("Півосі мають бути в (0; 1e100]."); // Перевіряємо параметри.
        // this — поточний об’єкт, аналог self у Python, але його не пишуть у списку параметрів. Ліворуч this.ім’я
        // — поле об’єкта, праворуч однойменне ім’я без this — переданий параметр; тому значення зберігається після
        // завершення конструктора.
        this.a = a; // Ініціалізуємо першу піввісь.
        this.b = b; // Ініціалізуємо другу піввісь.
    }
    // @Override просить компілятор перевірити, що метод справді замінює успадкований метод або реалізує метод
    // інтерфейсу. Якщо помилитися в назві чи параметрах, Java повідомить про це ще до запуску.
    @Override public double value(double x) { // Обчислюємо верхню гілку так само, як у задачі 2.
        if (!Double.isFinite(x) || Math.abs(x) < a) throw new IllegalArgumentException("x поза областю визначення."); // Перевіряємо аргумент.
        // Під коренем (|x|/a-1)(|x|/a+1), тобто (x/a)²-1. Розклад різниці квадратів зручніший біля |x|=a; sqrt
        // бере невід’ємний корінь, тому метод повертає лише верхню гілку гіперболи.
        double result = b * Math.sqrt((Math.abs(x) / a - 1) * (Math.abs(x) / a + 1)); // Безпосередня формула без делегування абстрактному класу.
        if (!Double.isFinite(result)) throw new ArithmeticException("Переповнення."); // Перевіряємо скінченність результату.
        return result; // Виконуємо контракт value.
    }
    @Override public void print(double x) { System.out.println(this + "; x=" + x + "; y=" + value(x)); } // Виконуємо контракт print.
    @Override public String toString() { return "HyperbolaViaInterface(a=" + a + ", b=" + b + ")"; } // Описуємо тип і стан.
    // instanceof одночасно перевіряє фактичний тип і дає змінній праворуч посилання потрібного типу. Це поєднання
    // Python isinstance(...) та присвоєння; для null перевірка дасть false. && не виконує праву частину, якщо тип
    // не підійшов, тому доступ до полів безпечний.
    // Double.compare(a, b) дає від’ємне число, 0 або додатне число залежно від порядку a і b. Для сортування
    // важливий знак; це безпечніше за (int)(a-b), бо невелика різниця не загубиться після відкидання дробової
    // частини.
    @Override public boolean equals(Object other) { return other instanceof HyperbolaViaInterface f && Double.compare(a, f.a) == 0 && Double.compare(b, f.b) == 0; } // Порівнюємо за значенням.
    // hashCode потрібен хеш-колекціям, приблизно як __hash__ у Python. Рівні за equals об’єкти обов’язково повинні
    // мати однаковий хеш; однаковий хеш сам по собі НЕ доводить рівність. Тут беремо ті самі значущі поля, що й у
    // equals.
    @Override public int hashCode() { return Objects.hash(a, b); } // Використовуємо ті самі поля, що й equals.
}
